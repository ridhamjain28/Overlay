// Overlay: minimal standards-compliant iCalendar (.ics) writer.
// No dependencies. Produces a single VEVENT in a VCALENDAR.
// Follows RFC 5545: CRLF line endings, 75-octet line folding.

"use strict";

const crypto = require("crypto");

// Fold long lines: max 75 octets, continuation lines start with a space.
function fold(line) {
  const bytes = Buffer.from(line, "utf8");
  if (bytes.length <= 75) return line;
  const parts = [];
  let start = 0;
  let first = true;
  while (start < bytes.length) {
    const max = first ? 75 : 74; // continuation lines have a leading space
    parts.push(bytes.slice(start, start + max).toString("utf8"));
    start += max;
    first = false;
  }
  return parts.join("\r\n ");
}

// Escape TEXT values (SUMMARY, DESCRIPTION).
function escapeText(str) {
  return String(str)
    .replace(/\\/g, "\\\\")
    .replace(/;/g, "\\;")
    .replace(/,/g, "\\,")
    .replace(/\n/g, "\\n");
}

// Format an ISO 8601 date-time as iCal UTC: 20260101T150000Z
function toUtc(isoStr) {
  const d = new Date(isoStr);
  const pad = (n) => String(n).padStart(2, "0");
  return (
    `${d.getUTCFullYear()}${pad(d.getUTCMonth() + 1)}${pad(d.getUTCDate())}` +
    `T${pad(d.getUTCHours())}${pad(d.getUTCMinutes())}${pad(d.getUTCSeconds())}Z`
  );
}

/**
 * Build a .ics string for a single event or reminder.
 *
 * @param {object} opts
 * @param {string}  opts.title
 * @param {string}  opts.start   — ISO 8601 with timezone offset
 * @param {string}  [opts.end]   — ISO 8601 with timezone offset; defaults to start + 30 min
 * @param {string}  [opts.description]
 * @param {string}  [opts.uid]   — override (tests); auto-generated by default
 * @param {string}  [opts.dtstamp] — override DTSTAMP (tests); defaults to now UTC
 * @returns {string}  CRLF-terminated iCalendar text
 */
function buildIcs({ title, start, end, description, uid, dtstamp }) {
  const startUtc = toUtc(start);
  const endUtc = end ? toUtc(end) : toUtc(new Date(Date.parse(start) + 30 * 60 * 1000).toISOString());
  const stamp = dtstamp || toUtc(new Date().toISOString());
  const eventUid = uid || `overlay-${crypto.randomUUID()}@overlay.local`;

  const lines = [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//Overlay//Overlay//EN",
    "CALSCALE:GREGORIAN",
    "METHOD:PUBLISH",
    "BEGIN:VEVENT",
    `UID:${eventUid}`,
    `DTSTAMP:${stamp}`,
    `DTSTART:${startUtc}`,
    `DTEND:${endUtc}`,
    fold(`SUMMARY:${escapeText(title)}`),
  ];

  if (description) {
    lines.push(fold(`DESCRIPTION:${escapeText(description)}`));
  }

  lines.push("END:VEVENT", "END:VCALENDAR");

  // RFC 5545 §3.1: lines MUST end with CRLF
  return lines.join("\r\n") + "\r\n";
}

module.exports = { buildIcs, fold, escapeText, toUtc };
